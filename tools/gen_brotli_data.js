// Generate woff2/src/brotli-data.js from google/brotli's c/common sources (a Node port of the
// former tools/gen_brotli_data.py; same parsing, same output). Parses the C tables mechanically
// so nothing is hand-transcribed. Called by scripts/fetch.js with the pinned upstream files;
// the output is gitignored and regenerated on every fresh clone.
import { createHash } from 'node:crypto';

/** All integer literals of a C initializer body, comments removed. */
const cInts = (body) => (body.replace(/\/\*[\s\S]*?\*\//g, '').match(/-?0x[0-9A-Fa-f]+|-?\d+/g) || [])
  .map((x) => (x.startsWith('-') ? -Number(x.slice(1)) : Number(x)));

/** Concatenated C string literals → bytes (\xNN, octal and the usual single-char escapes). */
function cString(litConcat) {
  const out = [];
  for (const m of litConcat.matchAll(/"((?:[^"\\]|\\.)*)"/g)) {
    const lit = m[1];
    let i = 0;
    while (i < lit.length) {
      const ch = lit[i];
      if (ch !== '\\') { out.push(ch.charCodeAt(0)); i++; continue; }
      const n = lit[i + 1];
      if (n === 'x') { const h = /^[0-9A-Fa-f]{1,2}/.exec(lit.slice(i + 2))[0]; out.push(parseInt(h, 16)); i += 2 + h.length; }
      else if (/[0-7]/.test(n)) { const o = /^[0-7]{1,3}/.exec(lit.slice(i + 1))[0]; out.push(parseInt(o, 8)); i += 1 + o.length; }
      else { out.push({ n: 10, t: 9, r: 13, '"': 34, "'": 39, '\\': 92 }[n]); i += 2; }
    }
  }
  return out;
}

/** Python's repr of a nested list of ints, which the generated file has always used. */
const repr = (x) => (Array.isArray(x) ? `[${x.map(repr).join(', ')}]` : String(x));

const must = (re, s, what) => { const m = re.exec(s); if (!m) throw new Error(`gen_brotli_data: ${what} not found`); return m[1]; };

/**
 * @param {{ 'transform.c': Buffer, 'transform.h': Buffer, 'context.c': Buffer, 'dictionary.c': Buffer, 'dictionary.bin': Buffer }} src
 * @param {string} sha google/brotli commit
 */
export function genBrotliData(src, sha) {
  const read = (p) => src[p].toString('latin1');
  const t = read('transform.c');
  const prefixSuffix = [...cString(must(/kPrefixSuffix\[\d+\]\s*=\s*([\s\S]*?);/, t, 'kPrefixSuffix')), 0];
  const psMap = cInts(must(/kPrefixSuffixMap\[\d+\]\s*=\s*\{([\s\S]*?)\};/, t, 'kPrefixSuffixMap'));
  const enumv = Object.fromEntries([...read('transform.h').matchAll(/(BROTLI_TRANSFORM_\w+)\s*=\s*(\d+)/g)].map((m) => [m[1], Number(m[2])]));
  const tsrc = must(/kTransformsData\[\]\s*=\s*\{([\s\S]*?)\};/, t, 'kTransformsData').replace(/\/\*[\s\S]*?\*\//g, '');
  const tdata = tsrc.match(/BROTLI_TRANSFORM_\w+|\d+/g).map((x) => (x in enumv ? enumv[x] : Number(x)));
  if (tdata.length !== 121 * 3) throw new Error(`gen_brotli_data: ${tdata.length} transform words`);
  // Entries are length-prefixed: [len][bytes...] (transform.c: prefix_len = *prefix++).
  const word = (i) => prefixSuffix.slice(psMap[i] + 1, psMap[i] + 1 + prefixSuffix[psMap[i]]);
  const transforms = Array.from({ length: 121 }, (_, k) => [word(tdata[3 * k]), tdata[3 * k + 1], word(tdata[3 * k + 2])]);

  const ctx = cInts(must(/_kBrotliContextLookupTable\[2048\]\s*=\s*\{([\s\S]*?)\};/, read('context.c'), 'context table'));
  if (ctx.length !== 2048) throw new Error(`gen_brotli_data: ${ctx.length} context entries`);

  const d = read('dictionary.c');
  const bits = cInts(must(/size_bits_by_length\s*\*\/\s*\{([\s\S]*?)\}/, d, 'size_bits_by_length'));
  const offs = cInts(must(/offsets_by_length\s*\*\/\s*\{([\s\S]*?)\}/, d, 'offsets_by_length'));
  if (bits.length !== 32 || offs.length !== 32) throw new Error(`gen_brotli_data: ${bits.length}/${offs.length} length entries`);
  const dic = src['dictionary.bin'];
  if (dic.length !== 122784) throw new Error(`gen_brotli_data: dictionary is ${dic.length} bytes`);
  const h = createHash('sha256').update(dic).digest('hex');

  return `// GENERATED by tools/gen_brotli_data.js from google/brotli @ ${sha} (MIT). Do not edit.
// RFC 7932 Appendix A (dictionary), B (transforms), §7.1 (context lookup).
// Brotli is MIT licensed; npm run fetch saves its notice to third_party/licenses/brotli-LICENSE.
// dictionary.bin sha256 ${h}

/** Static dictionary, 122784 bytes. */
export const DICTIONARY_BASE64 = '${dic.toString('base64')}';
export const DICTIONARY_SHA256 = '${h}';
/** log2(word count) per word length (0..31). */
export const NDBITS = Object.freeze(${repr(bits)});
/** Byte offset of the first word of each length. */
export const DICT_OFFSETS = Object.freeze(${repr(offs)});
/**
 * 121 transforms: [prefix bytes, type, suffix bytes]. Types: 0 identity, 1-9 omit last n,
 * 10 uppercase first, 11 uppercase all, 12-20 omit first (type - 11).
 * @type {ReadonlyArray<readonly [number[], number, number[]]>}
 */
export const TRANSFORMS = Object.freeze(${repr(transforms)});
/** 4 modes (LSB6, MSB6, UTF8, Signed) × [256 for p1, 256 for p2]; context = T[m·512 + p1] | T[m·512 + 256 + p2]. */
export const CONTEXT_LOOKUP = Object.freeze(${repr(ctx)});
`;
}
