// Generate shape/src/ccc-data.js: HarfBuzz's *modified* canonical combining class per codepoint,
// as ranges, for mark reordering (hb-ot-shape-normalize.cc, second round). A Node port of the
// former tools/gen_ccc.py; called by scripts/fetch.js with the pinned upstream files.
//
// Unicode combining classes come from UnicodeData.txt (field 3); HarfBuzz's remapping (the
// 256-entry _hb_modified_combining_class table with its HB_MODIFIED_COMBINING_CLASS_CCC* macros,
// and the three special codepoints in hb-unicode.hh) is parsed from the HarfBuzz source, not
// copied by hand.

/**
 * @param {{ 'hb-unicode.cc': Buffer, 'hb-unicode.hh': Buffer, 'UnicodeData.txt': Buffer }} src
 * @param {string} sha harfbuzz commit
 * @param {string} unicodeVersion e.g. '15.1.0'
 */
export function genCcc(src, sha, unicodeVersion) {
  const cc = src['hb-unicode.cc'].toString('utf8'), hdr = src['hb-unicode.hh'].toString('utf8');
  const macros = Object.fromEntries([...hdr.matchAll(/#define (HB_MODIFIED_COMBINING_CLASS_CCC\d+) (\d+)/g)].map((m) => [m[1], Number(m[2])]));
  const m = /_hb_modified_combining_class\[256\] =\s*\{([\s\S]*?)\n\};/.exec(cc);
  if (!m) throw new Error('gen_ccc: _hb_modified_combining_class not found');
  const table = m[1].replace(/\/\*[\s\S]*?\*\//g, '').split(',').map((x) => x.trim()).filter(Boolean)
    .map((t) => (t in macros ? macros[t] : Number(t)));
  if (table.length !== 256 || table.some((v) => !Number.isInteger(v))) throw new Error(`gen_ccc: table has ${table.length} entries`);
  const special = new Map([...hdr.matchAll(/if \(unlikely \(u == 0x([0-9A-F]+)u\)\) return (\d+);/g)].map((x) => [parseInt(x[1], 16), Number(x[2])]));
  if (special.size !== 3) throw new Error(`gen_ccc: ${special.size} special codepoints`);

  // UnicodeData.txt: code;name;gc;ccc;... (First/Last range rows all have ccc 0).
  const ccc = new Map();
  for (const line of src['UnicodeData.txt'].toString('utf8').split('\n')) {
    if (!line) continue;
    const f = line.split(';');
    const c = Number(f[3]);
    if (c) ccc.set(parseInt(f[0], 16), c);
  }

  const ranges = [];
  for (let cp = 0; cp < 0x110000; cp++) {
    const c = ccc.get(cp) || 0;
    const v = special.has(cp) ? special.get(cp) : c ? table[c] : 0;
    if (!v) continue;
    const last = ranges[ranges.length - 1];
    if (last && last[1] === cp - 1 && last[2] === v) last[1] = cp;
    else ranges.push([cp, cp, v]);
  }
  const flat = ranges.map(([a, b, v]) => `${a},${b},${v}`).join(',');
  return `// @ts-check
// GENERATED by tools/gen_ccc.js — do not edit. HarfBuzz's modified canonical combining class
// (hb-unicode.cc _hb_modified_combining_class, harfbuzz@${sha.slice(0, 7)}) over Unicode ${unicodeVersion}
// combining classes (UnicodeData.txt). Flat [start, end, class] ranges, sorted; ${ranges.length} ranges.
// HarfBuzz is "Old MIT" licensed (third_party/licenses/harfbuzz-COPYING). Unicode data: Unicode License v3.
export const CCC_RANGES = Object.freeze([${flat}]);
`;
}
